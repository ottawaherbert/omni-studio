export const getStageDefinitions = (mode: ProductionMode) =>
  mode === "interactive" ? interactiveStageDefinitions : linearStageDefinitions;

export const createStageRuns = (
  runId: string,
  mode: ProductionMode,
  policy: ProductionPolicy,
): ProductionStageRun[] =>
  getStageDefinitions(mode).map((definition, index) => ({
    id: `${runId}-stage-${index + 1}-${definition.stageType}`,
    runId,
    stageType: definition.stageType,
    title: definition.title,
    description: definition.description,
    agentId: definition.agentId,
    status: "pending",
    outputArtifactIds: [],
    qaReports: [],
    gateVerdicts: [],
    recoverySuggestions: [],
    retryCount: 0,
    maxRetries: policy.maxRetriesPerStage,
    schemaVersion: "production-stage-v1",
    authoritySnapshotStatus: "none",
    nextAction: index === 0 ? "点击继续后开始执行本阶段。" : "等待前置阶段完成。",
    requiresHumanReview: policy.manualGates.includes(definition.stageType),
  }));

export const isTerminalStageStatus = (status: string) =>
  status === "completed" || status === "skipped" || status === "failed";

export const getNextRunnableStage = (
  stages: ProductionStageRun[],
  currentStageId: string,
) => {
  const currentIndex = stages.findIndex((stage) => stage.id === currentStageId);
  if (currentIndex === -1) return stages.find((stage) => stage.status === "pending");
  return stages.slice(currentIndex + 1).find((stage) => stage.status === "pending");
};

