assert.ok(workOnlyPrompt.includes('只返回 JSON 对象'));
assert.ok(workOnlyPrompt.includes('director-profile.v2'));
assert.ok(workOnlyPrompt.includes('不把导演其他作品的方法混入'));
assert.ok(workOnlyPrompt.includes('可用于不同故事的导演方法 Skill'));
assert.ok(workOnlyPrompt.includes('本次无需提供待拍剧本'));
assert.ok(workOnlyPrompt.includes('具体场景中的应用由后续制片流程决定'));
assert.ok(!/保留正式剧本|已确认的镜头|已确认画风|三人会议|示范正文片段|根据参考作品或图片提取/.test(workOnlyPrompt));
assert.ok(!workOnlyPrompt.includes('先核对每条方法的适用条件；条件不存在就跳过'));
assert.ok(workOnlyPrompt.includes('productionDesign.characterAppearance'));
assert.throws(() => buildCreativeSkillDraftPrompt({kind:'director',content:'',references:[]}), /请输入参考作品/);
assert.throws(() => creativeSkillDraftText(' \n '), /返回内容为空/);
const raw = '参考《大话西游之月光宝盒》的呈现方法，剧本已有误会时，先呈现既定行为，再切承受者反应。\n\n条件不存在时跳过。';
assert.equal(creativeSkillDraftText('  '+raw+'  '),raw); // No title equality gate; preserve paragraphs.
assert.equal(creativeSkillDraftTitle('director',referenceWork),'大话西游 · 导演方法');
assert.equal(creativeSkillDraftTitle('visual_style'),'自定义画风');
const portable = { title: creativeSkillDraftTitle('director',referenceWork), content: raw, referenceWork, profile: {} };
const downstreamPortable = renderProductionCreativeContext({id:'portable',characters:[],assets:[],creativeDirection:{director:{mode:'replace',skill:snapshotCreativeSkill({...portable,id:'portable-skill',kind:'director',source:'manual',createdAt:1,updatedAt:1})}}},{},'planning');
assert.ok(downstreamPortable.includes(raw));
assert.ok(downstreamPortable.includes('不得因此新增笑料、误会、突发事件'));
assert.throws(() => buildCreativeSkillDraftPrompt({kind:'visual_style',content:'宫崎骏风格',references:[]}), /直接填写风格提示词/);
// Minimal persisted visual snapshots cover backwards compatibility; no visual preset catalog remains.
const presets = [
 {id:'legacy-live',title:'旧实拍画风',medium:'live_action' as const},
 {id:'legacy-cartoon',title:'旧二维画风',medium:'2d_animation' as const},
 {id:'builtin-visual-79',title:'旧混合媒介',medium:'mixed_media' as const},
].map(item => ({id:item.id,title:item.title,kind:'visual_style' as const,content:'蓝灰配色与纸面纹理',source:'manual' as const,createdAt:1,updatedAt:1,profile:{visual:{medium:item.medium,...(item.medium==='mixed_media'?{subjectMedium:'3d_animation' as const,backgroundMedium:'3d_animation' as const}:{}),treatment:{directives:['蓝灰配色与纸面纹理'],color:['蓝灰配色'],linework:['柔和轮廓']}}}}));
for (const preset of presets) validateCreativeSkill(preset);
const live = snapshotCreativeSkill(presets.find(s => s.kind === 'visual_style' && s.profile?.visual?.medium === 'live_action')!);
const cartoon = snapshotCreativeSkill(presets.find(s => s.kind === 'visual_style' && s.profile?.visual?.medium === '2d_animation')!);
cartoon.references = [{ id:'r', url:'/media/style-test.png', label:'水彩参考', purpose:'只借线条与色块' }];
const director = snapshotCreativeSkill({id:'test-director',title:'验收导演方法',kind:'director',content:'用稳定机位观察人物关系，在听者反应之后切镜。',source:'manual',createdAt:1,updatedAt:1});
const shot = { id:'sh', characterIdsInShot:['c'], propIds:[], visualAction:'人物拿起杯子', duration:5 } as Shot;
const scene = { id:'sc', title:'屋内', shots:[shot] } as Scene;
const episode = { id:'ep', title:'第一集', scenes:[scene] } as Episode;
const project = { id:'p', title:'回归测试', characters:[{ id:'c',name:'阿青' }],assets:[],episodes:[episode], creativeDirection:{director:{mode:'replace',skill:director},visual:{mode:'replace',skill:live}},visualStyleLock:applyCreativeVisualBinding(undefined,{mode:'replace',skill:live}) } as unknown as Project;
assert.ok(renderProductionCreativeContext(project,{episode,scene,shot},'planning').includes(director.title));
assert.equal(resolveCreativeRole([{label:'全剧',bindings:project.creativeDirection},{label:'本镜',bindings:{director:{mode:'off'}}}], 'director').enabled,false);
const localShot = { ...shot, creativeDirection:{ visual:{mode:'replace' as const,skill:cartoon} } };
assert.equal(resolveProductionCreativeVisual(project,{episode,scene,shot:localShot})?.visualImplementation.productionMode,'2d_animation');
assert.equal(project.visualStyleLock?.visualImplementation.productionMode,'live_action');
assert.equal(resolveProductionCreativeVisual(project,{episode:{...episode,creativeDirection:{visual:{mode:'replace',skill:cartoon}}},shot})?.visualImplementation.productionMode,'2d_animation');
assert.equal(resolveProductionCreativeVisual(project,{shot:{...shot,creativeDirection:{visual:{mode:'off'}}}}),undefined);
const borrowed = resolveProductionCreativeVisual(project,{shot:{...shot,creativeDirection:{visual:{mode:'replace',skill:cartoon,visualSections:['color','palette']}}}});
assert.equal(borrowed?.visualImplementation.productionMode,'live_action');
const mixedShot = { ...shot, creativeDirection:{objects:{c:{mode:'replace' as const,skill:cartoon}}} };
const mixed = resolveProductionCreativeVisual(project,{episode,scene,shot:mixedShot});
assert.equal(mixed?.visualImplementation.productionMode,'mixed_media');
assert.equal(mixed?.mediumAssignments?.find(a => a.id === 'creative-object-c')?.implementation.productionMode,'2d_animation');
const image = buildImageVisualStyleProjection({project,creativeScope:{episode,scene,shot:mixedShot},intent:'final_frame',targets:[{entityId:'c',entityType:'character'}]});
assert.equal(image.styleReferences?.[0].role,'style_reference');
assert.ok(image.styleReferences?.[0].preserve[0].includes('阿青'));
const board = buildImageVisualStyleProjection({ project, intent:"storyboard_control", creativeScope:{episode,scene:{...scene,shots:[shot,mixedShot]}} });
assert.ok(board.instruction.includes("第 2 镜专用规范"));
assert.ok(board.styleReferences?.[0].preserve.some(rule=>rule.includes("第 2 镜")));
assert.ok(!board.styleReferences?.[0].preserve.some(rule=>rule.includes("第 1 镜")));
const compiled = compileImageGenerationRequest({promptCore:'一个人物在室内拿起杯子，清晰呈现动作。',visualStyleProjection:image});
assert.ok(compiled.referenceImages.includes('/media/style-test.png'));
assert.ok(compiled.providerPrompt.includes('只借线条与色块'));
assert.ok(!compiled.providerPrompt.includes('/media/style-test.png'));
const video = buildStudioShotVideoVisualStyleProjection({project,episode,scene,shot:localShot});
assert.ok(video.rendered.instruction.includes('人物拿起杯子'));
assert.ok(!video.rendered.instruction.includes(director.content));
assert.equal(video.projection.implementation.productionMode,'2d_animation');
const assetProject = structuredClone(project);
assetProject.characters[0].creativeDirection={visual:{mode:'replace',skill:cartoon}};
const asset = buildProductionAssetImageVisualStyleProjection({project:assetProject,asset:{assetId:'c',assetType:'character',assetName:'阿青'}});
assert.ok(asset.instruction.length);
assert.equal(asset.styleReferences?.length,1);
const followedAsset = resolveProductionCreativeVisual(assetProject, { shot: { ...shot, creativeDirection: { objects: { c: { mode: "inherit" } } } } });
assert.equal(followedAsset?.mediumAssignments?.find(item => item.id === "creative-object-c")?.implementation.productionMode, "2d_animation");
const changedDirector = structuredClone(project);
changedDirector.creativeDirection!.director!.notes = "只保留固定机位";
assert.equal(buildStudioShotVideoVisualStyleProjection({project:changedDirector,episode,scene,shot}).rendered.manifest.creativeDirection?.sourceHash, buildStudioShotVideoVisualStyleProjection({project,episode,scene,shot}).rendered.manifest.creativeDirection?.sourceHash);
const punk = snapshotCreativeSkill(presets.find(item => item.id === "builtin-visual-79")!);
const punkObject = resolveProductionCreativeVisual(project,{shot:{...shot,creativeDirection:{objects:{c:{mode:"replace",skill:punk}}}}});
assert.equal(punkObject?.mediumAssignments?.find(item=>item.id === "creative-object-c")?.implementation.productionMode,"3d_animation");
assert.equal(creativeStyleReferences(project,{request:{visual:{mode:'off'}}}).length,0);
const textBinding = {mode:'replace' as const,stylePrompt:'宫崎骏风格'};
const textProject = {...project,creativeDirection:{...project.creativeDirection,visual:textBinding},visualStyleLock:applyCreativeVisualBinding(project.visualStyleLock,textBinding)};
assert.ok(!('skill' in textProject.creativeDirection.visual));
const textImage = buildImageVisualStyleProjection({project:textProject,intent:'final_frame'});
