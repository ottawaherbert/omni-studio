try {
 const manualMedium = await createSkillFile(dir,{id:'manual-medium',title:'手动媒介',content:'三维体积',kind:'visual_style',profile:{visual:{medium:'3d_animation',mediumSelection:'manual',treatment:{directives:['三维体积']}}}});
 const manualEdited = await updateSkillFile(dir,manualMedium.id,{content:'三维体积与硬边轮廓'});
 assert.equal(manualEdited?.profile?.visual?.mediumSelection,'manual');
 assert.equal((await readSkills(dir)).find(s=>s.id===manualMedium.id)?.profile?.visual?.medium,'3d_animation');
 const portableSaved = await createSkillFile(dir,{...portable,id:'portable',kind:'director'});
 assert.equal((await readSkills(dir)).find(s=>s.id===portableSaved.id)?.content,raw);
 const saved = await createSkillFile(dir,{id:'watercolor',title:'水彩参考',content:'明确的水彩晕染',kind:'visual_style',profile:cartoon.profile,references:cartoon.references,referenceWork});
 const read = (await readSkills(dir)).find(s => s.id === saved.id)!;
 assert.deepEqual(read.referenceWork,referenceWork);
 assert.deepEqual(snapshotCreativeSkill(read).referenceWork,referenceWork);
 assert.deepEqual(read.profile,cartoon.profile);
 assert.deepEqual(read.references,cartoon.references);
 assert.equal(read.revision,1);
 const pinned = snapshotCreativeSkill(read);
 const edited = await updateSkillFile(dir,saved.id,{content:'改为粗糙炭笔'});
 assert.equal(edited?.revision,2);
 assert.deepEqual(edited?.referenceWork,referenceWork);
 const cleared = await updateSkillFile(dir,saved.id,{referenceWork:null});
 assert.equal((await readSkills(dir)).find(s=>s.id===cleared!.id)?.referenceWork,undefined);
 assert.equal(pinned.content,'明确的水彩晕染');
 assert.deepEqual(edited?.profile?.visual?.treatment.directives,['改为粗糙炭笔']);
} finally {await rm(dir,{recursive:true,force:true});}
