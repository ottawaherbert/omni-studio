import assert from 'node:assert/strict';
import type { Character, Episode, Project } from '../src/types/project';
import { characterProfileProposal, characterProfileChangedSincePreview, characterProfileTaskInstruction } from '../src/services/production/productionCharacterProfile';
import { buildProductionAssetProfileContext } from '../src/services/production/productionAssetProfileContext';
import { characterSpeechDirection, resolveTrackVoiceDirection, voiceDirectionOverrides } from '../src/utils/studioVoiceResult';
import { defaultTemplates } from '../src/config/prompts';

const actor = { id: 'qing', name: '阿青', mbti: 'ENTJ', externalGoal: '作者已定的长期目标', visualIdentity: '' } as Character;
const firstScript = '阿青短发，穿白衬衣。这次被追问时移开视线。';
const project = { characters: [actor], productionSourceDocuments: [{ id: 'one', title: '第一集', content: firstScript }] } as Project;
const episode = { id: 'ep1', title: '第一集', scenes: [{ id: 's1', title: '询问', script: firstScript, shots: [] }] } as unknown as Episode;
const context = buildProductionAssetProfileContext(project, { ...actor, kind: 'character' }, [episode]);
assert.ok(context.options.some(option => option.value.includes(firstScript)), 'direct production without breakdown still supplies source');
assert.ok(context.options.some(option => option.label.includes('导入原文')), 'a scene binding must not hide the imported source');
assert.ok(context.options.every(option => !option.value.includes('第二集')));
const proposal = characterProfileProposal({ visualIdentity: '短发，白衬衣', psychologicalProfile: '天生逃避', externalGoal: '解救全世界', mbti: 'INTJ', sliders: { 恐惧: 10 }, actingStyle: '', vocalQuirk: null }, actor as unknown as Record<string, unknown>, 'extract');
assert.deepEqual(proposal, { visualIdentity: '短发，白衬衣' }, 'legacy personality/goal output cannot enter production extraction');
assert.equal(actor.mbti, 'ENTJ');
assert.equal(actor.externalGoal, '作者已定的长期目标');
assert.deepEqual(characterProfileProposal({ visualIdentity: '长发', actingStyle: {} }, { visualIdentity: '作者确认的短发' }, 'extract'), {}, 'extraction fills gaps without overwriting author text or coercing objects');
assert.deepEqual(characterProfileProposal({ visualIdentity: '', sourceNotes: '当前材料不足' }, {}, 'extract'), {}, 'unknown is a valid no-change result');
const design = characterProfileProposal({ visualIdentity: '椭圆脸', actingStyle: '激烈表演', flaw: '自卑' }, { visualIdentity: '短发，白衬衣' }, 'appearance');
assert.deepEqual(design, { visualIdentity: '短发，白衬衣\n【外观设计】椭圆脸' }, 'design preserves existing anchors and cannot change psychology or performance');
assert.equal(characterProfileChangedSincePreview({ ...actor, visualIdentity: '手动新内容' }, { visualIdentity: '' }, ['visualIdentity']), true);
assert.equal(characterProfileChangedSincePreview(actor, { visualIdentity: '' }, ['visualIdentity']), false);
assert.match(characterProfileTaskInstruction('extract'), /单次行为不能归纳为长期性格/);
assert.match(defaultTemplates.productionAssetCharacterProfile.template, /只导入第一集就只知道第一集/);
assert.doesNotMatch(defaultTemplates.productionAssetCharacterProfile.template, /3-5 个|评分不低于 90/);
const defaults = { instructions: '平稳', language: 'Chinese' };
const track = { voiceDirection: { instructions: '本句急促' } } as Parameters<typeof resolveTrackVoiceDirection>[1];
const authored = resolveTrackVoiceDirection(defaults, track);
const spoken = characterSpeechDirection('习惯慢速、句尾收住', authored.instructions);
assert.match(spoken, /习惯慢速/);
assert.match(spoken, /本句急促/);
assert.match(spoken, /本句明确的情绪、语速与表演要求优先/);
assert.match(spoken, /不新增口头禅、语气词或改写台词/);
assert.deepEqual(voiceDirectionOverrides(authored, defaults).instructions, '本句急促', 'persist author overrides, not a frozen copy of inherited character instructions');
assert.equal(characterSpeechDirection(undefined, '本句要求'), '本句要求');
assert.equal(characterSpeechDirection(undefined, undefined), '');
console.log('Character profile workflow passed: partial sources, unknowns, author preservation, scoped designs, stale preview and speech inheritance.');
