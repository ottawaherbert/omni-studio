 assert.equal(edited.skill.revision,2);
 assert.equal(edited.skill.profile.director.editing,'反应后切镜');
 assert.equal(edited.skill.analysisBasis,'provided_analysis');
 assert.equal(edited.skill.analysisNotes,'虚构测试分析，不是原片观察');
 // Explicit empty profile must survive HTTP even when regenerated prose is unchanged.
