 assert.equal(shell.episodes[0].creativeDirection.director.notes,'本集反应要克制');
 const workspace=await request(`/api/projects/${project.id}/episodes/${episode.id}?view=storyboard&sceneId=creative-scene`);
 assert.equal(workspace.creativeDirection.director.notes,'本集反应要克制');
 assert.equal(workspace.scenes[0].creativeDirection.director.notes,'保留走廊画外声');
