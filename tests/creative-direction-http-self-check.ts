 const scene = episode.scenes[0];
 const directed = normalizeDirectorPlan({project,episode,scene,shots:scene.shots!,rawShots:[{directorPlan:{intent:'观察拿杯后的反应',rhythm:'动作后留下反应时间',applications:[{method:'用稳定机位观察人物关系',evidence:'阿青坐在窗边拿起杯子',decision:'维持中景直到动作停止',shotNumbers:[1]}],exceptions:[]}}]});
 scene.shots=directed.shots;
 scene.manualStoryboard={schemaVersion:'manual-storyboard.v1',directorPlan:directed.plan,updatedAt:Date.now()};
 await request('/api/projects',project);
