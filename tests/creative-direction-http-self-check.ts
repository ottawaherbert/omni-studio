import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import express from 'express';
import { createProductionProjectFromMagicSource } from '../src/services/production/productionSourceIntake';
import { snapshotCreativeSkill, directorProfileText } from '../packages/domain/src/creativeDirection';
