import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import Database from 'better-sqlite3';
import express from 'express';
import { createScriptRuntime } from '../apps/api/src/agent/scriptRuntime';
import { createScriptProject, newUnit } from '../packages/script/src/project';
import { createScriptCreationProfile } from '../packages/script/src/creation';

test('real workspace HTTP persists an unpublished multi-unit draft, restart, adopt once, fixed execution export and paired author baseline',async()=>{
  const dir=mkdtempSync(path.join(tmpdir(),'script-workspace-http-')),filename=path.join(dir,'test.sqlite');
  const start=async()=>{
    const db=new Database(filename),runtime=createScriptRuntime(db,{owner:req=>req.get('x-test-owner')||'http-author',resolveMethods:async()=>[],resolveExecution:()=>({channel:'external',routeRef:'mechanical'}),transport:{sendOnce:async()=>{throw new Error('No model in author HTTP acceptance');}}});
    const {scripts,conversations}=runtime;
    const thread=conversations.open('http-author','script:home','workspace-http');
    const otherThread=conversations.open('another','script:home','workspace-http-foreign');
    const app=express();app.use(express.json());runtime.register(app);
    const server=app.listen(0,'127.0.0.1');await once(server,'listening');const base=`http://127.0.0.1:${(server.address() as any).port}`;
    const api=async(route:string,body?:unknown,method=body?'POST':'GET',status=200,owner='http-author')=>{const response=await fetch(base+route,{method,headers:{'Content-Type':'application/json','x-test-owner':owner},...(body?{body:JSON.stringify(body)}:{})});const data=await response.json();assert.equal(response.status,status,JSON.stringify(data));return data as any;};
    const close=async()=>{await runtime.stop();await new Promise<void>((resolve,reject)=>server.close(e=>e?reject(e):resolve()));db.close();};
    return {api,thread,otherThread,scripts,close};
  };
  let h=await start();
  try{
    const source=createScriptProject('【隔离HTTP验收】',createScriptCreationProfile('tv-series',3,20));source.units[0].scenes[0].blocks[0].text='【人工原文】 第一场\n不丢空格。';
    const create={threadId:h.thread.id,requestId:'create',source:{document:source}};
    const w=(await h.api('/api/script-workspaces',create,'POST',201)).workspace;
    await h.api(`/api/agent/scopes/${w.id}/memories?branch=workspace:${w.id}`,undefined,'GET');
    await h.api(`/api/agent/scopes/${w.id}/memories?branch=workspace:${w.id}`,undefined,'GET',404,'another');
    assert.equal(h.scripts.listProjects().length,0);assert.equal((await h.api('/api/script-workspaces',create,'POST',201)).workspace.id,w.id);
    const next=structuredClone(w.document);next.units.push(newUnit('第2集',1200000,next.id));next.units[1].scenes[0].blocks[0].text='【协议测试】第二集稿件';
    const save={requestId:'save',expectedRevision:1,expectedEpoch:1,document:next};await h.api(`/api/script-workspaces/${w.id}`,save,'PUT');
    await h.close();h=await start();
    assert.equal((await h.api(`/api/script-workspaces/${w.id}`)).workspace.revision,2);
    await h.api(`/api/script-workspaces/${w.id}`,undefined,'GET',404,'another');
    assert.equal((await h.api(`/api/script-workspaces/${w.id}`,save,'PUT')).workspace.revision,2);
    await h.api(`/api/script-workspaces/${w.id}`,{...save,requestId:'stale'},'PUT',409);
    const proposal=(await h.api(`/api/script-workspaces/${w.id}/merge`,{workspaceRevision:2,expectedAuthorRevision:0})).proposal;
    const adoption={requestId:'adopt',proposalId:proposal.id,digest:proposal.digest};const receipt=(await h.api(`/api/script-workspaces/${w.id}/adopt`,adoption)).receipt;
    assert.deepEqual((await h.api(`/api/script-workspaces/${w.id}/adopt`,adoption)).receipt,receipt);assert.equal(h.scripts.getProject(w.documentId)!.revision,1);
    await h.api('/api/script-workspaces',{threadId:h.otherThread.id,requestId:'foreign-project-import',source:{projectId:w.documentId,revision:1}},'POST',404,'another');
    await h.api(`/api/agent/scopes/${w.documentId}/memories?branch=author`,undefined,'GET',403,'another');
    const current=(await h.api(`/api/script-workspaces/${w.id}`)).workspace;
    assert.equal(current.document.units.length,2);
    assert.deepEqual((await h.api(`/api/script-workspaces/${w.id}/author-baseline`)).document,h.scripts.getProject(w.documentId));
    await h.api(`/api/script-workspaces/${w.id}/author-baseline`,undefined,'GET',404,'another');
    const exported=await h.api(`/api/script-workspaces/${w.id}/export`,{revision:2,unitIds:[next.units[1].id],format:'fountain'});
    assert.equal(exported.ref.version,'2');assert.match(exported.text,/第二集稿件/);assert.doesNotMatch(exported.text,/不丢空格/);
    const author=h.scripts.getProject(w.documentId)!;author.units[0].scenes[0].title='【HTTP作者直接改场】';h.scripts.saveProject(author,1);
    const sync={requestId:'http-sync',expectedRevision:current.revision,expectedEpoch:current.writerEpoch,expectedAuthorRevision:2};
    const synced=await h.api(`/api/script-workspaces/${w.id}/sync-author`,sync);
    assert.equal(synced.workspace.document.units[0].scenes[0].title,'【HTTP作者直接改场】');
    assert.equal(synced.workspace.baseProjectRevision,2);
    assert.deepEqual(await h.api(`/api/script-workspaces/${w.id}/sync-author`,sync),synced);
    await h.api(`/api/script-workspaces/${w.id}/sync-author`,{...sync,requestId:'stale-sync'},'POST',409);
    await h.api(`/api/script-workspaces/${w.id}/sync-author`,{...sync,requestId:'foreign-sync'},'POST',404,'another');
    assert.equal((await h.api(`/api/script-workspaces/${w.id}/revisions/1`)).document.units[0].scenes[0].blocks[0].text,source.units[0].scenes[0].blocks[0].text);

    const workspaceEdit=structuredClone(synced.workspace.document);
    workspaceEdit.units[0].scenes[0].title='【机械 AI 选择】';
    const draft=(await h.api(`/api/script-workspaces/${w.id}`,{requestId:'conflict-draft',expectedRevision:synced.workspace.revision,
      expectedEpoch:synced.workspace.writerEpoch,document:workspaceEdit},'PUT')).workspace;
    const authorEdit=h.scripts.getProject(w.documentId)!;
    authorEdit.units[0].scenes[0].title='【机械作者选择】';
    authorEdit.units[0].scenes[0].blocks[0].text='【机械作者独立正文】';
    h.scripts.saveProject(authorEdit,2);
    const mergeInput={workspaceRevision:draft.revision,expectedAuthorRevision:3};
    const preview=await h.api(`/api/script-workspaces/${w.id}/merge`,mergeInput);
    assert.equal(preview.proposal,null);assert.equal(preview.conflicts.length,1);
    assert.equal(preview.conflicts[0].authorValue,'【机械作者选择】');
    assert.equal(preview.conflicts[0].workspaceValue,'【机械 AI 选择】');
    assert.equal(h.scripts.getProject(w.documentId)!.units[0].scenes[0].title,'【机械作者选择】');
    await h.api(`/api/script-workspaces/${w.id}/merge`,{...mergeInput,resolutions:'WORKSPACE'},'POST',400);
    await h.api(`/api/script-workspaces/${w.id}/merge`,{...mergeInput,resolutions:[]},'POST',409);
    await h.api(`/api/script-workspaces/${w.id}/merge`,{...mergeInput,resolutions:[{id:'stale-id',choice:'WORKSPACE'}]},'POST',409);
    const authorChoice=(await h.api(`/api/script-workspaces/${w.id}/merge`,{...mergeInput,resolutions:[{id:preview.conflicts[0].id,choice:'AUTHOR'}]})).proposal;
    assert.equal(authorChoice.document.units[0].scenes[0].title,'【机械作者选择】');
    const workspaceChoice=(await h.api(`/api/script-workspaces/${w.id}/merge`,{...mergeInput,resolutions:[{id:preview.conflicts[0].id,choice:'WORKSPACE'}]})).proposal;
    assert.equal(workspaceChoice.document.units[0].scenes[0].title,'【机械 AI 选择】');
    assert.equal(workspaceChoice.document.units[0].scenes[0].blocks[0].text,'【机械作者独立正文】');
    const adoptedChoice=(await h.api(`/api/script-workspaces/${w.id}/adopt`,{requestId:'adopt-conflict-choice',proposalId:workspaceChoice.id,digest:workspaceChoice.digest})).receipt;
    assert.equal(adoptedChoice.projectRevision,4);
    assert.equal(h.scripts.getProject(w.documentId)!.units[0].scenes[0].title,'【机械 AI 选择】');
    assert.equal(h.scripts.getProject(w.documentId)!.units[0].scenes[0].blocks[0].text,'【机械作者独立正文】');
  }finally{await h.close();rmSync(dir,{recursive:true,force:true});}
});
