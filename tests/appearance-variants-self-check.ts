import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import Database from 'better-sqlite3';
import type { Project, Shot } from '../src/types/project';
import { appearanceAssetPatch, appearanceBoards, appearanceContentHash, appearanceIssues, appearanceFingerprint, materializeAppearanceVariants, normalizeShotAppearances } from '../src/services/production/productionAppearance';
import { buildManualShotPlanHash, buildManualVisualPromptSourceHash } from '../src/services/production/manualStoryboard';
import { cleanupAppearanceVariants } from '../src/services/production/appearanceVariantCleanup';
import { upgradeAppearanceTemplate } from '../src/config/prompts/appearanceContract';
import { rebaseAppearanceBookkeeping, repairAppearanceVariants } from '../tools/repair-appearance-variants';

const project = { id: 'p', characters: [{ id: 'c', name: '角色', referenceImageUrl: '/base.png', variants: [] }], assets: [], episodes: [] } as unknown as Project;
const scene = { id: 's', script: '他换上黑外套，手指少量出血。' } as any;
const shot = (id: string) => ({ id, characterIdsInShot: ['c'] } as Shot);
const raw = (extra = {}) => ({ appearance: { states: [{ assetId: 'c', timelineKey: '主线', origin: 'script', evidence: scene.script, continuity: 'new', startChanges: { clothing: '黑外套' }, endChanges: {}, referenceNeed: 'text', ...extra }] } });
const normalize = (values: any[]) => normalizeShotAppearances(project, scene, values.map((_, i) => shot(`s${i}`)), values);
const text = appearanceAssetPatch(project, normalize([raw(), raw({ startChanges: { clothing: '沿用基础服装' }, endChanges: { injury: '指尖少量血迹' } })]));
assert.equal(text.characters[0].variants!.length, 0, 'text-only adoption must not create even an initial variant');
assert.equal(text.shots[1].appearance!.states[0].end.injury, '指尖少量血迹');
assert.equal(appearanceBoards(project, text.shots, [], 'video').length, 3, 'different text states sharing the same base image retain their own prompts');
assert(appearanceBoards(project, text.shots, [], 'video').every(b => b.referenceImageUrl === '/base.png'));
assert.equal(appearanceBoards(project, [text.shots[0], { ...text.shots[0], id: 'same-look-next-shot' }], [], 'image').length, 1, 'identical visual requirements share a single reference binding');
const adopted = appearanceAssetPatch(project, normalize([raw({ referenceNeed: 'image' }), raw({ continuity: 'continue', inheritFromShotId: 'previous', startChanges: {}, endChanges: { injury: '指尖少量血迹' } })]));
assert.equal(adopted.characters[0].variants!.length, 1);
const variant = adopted.characters[0].variants![0];
assert.equal(adopted.shots[1].appearance!.states[0].endVariantId, variant.id, 'text overlay inherits actual preceding look within a single adoption');
const next = { ...project, characters: adopted.characters };
assert(!appearanceIssues(next, scene, adopted.shots[1], adopted.shots).some(i => /状态不同/.test(i.message)));
assert.equal(materializeAppearanceVariants(next, adopted.shots).characters[0].variants!.length, 1);
const auto = appearanceAssetPatch(project, normalize([raw({ referenceNeed: 'image', endChanges: { injury: '指尖少量血迹' } })]));
const oldProject = { ...project, characters: auto.characters };
const oldShots = structuredClone(auto.shots);
oldShots[0].appearance!.states[0].referenceNeed = 'text';
const hashes = oldShots.map(s => appearanceContentHash(s, 'video'));
const clean = cleanupAppearanceVariants(oldProject, oldShots);
assert.equal(clean.retired.length, 2);
assert.equal(clean.project.characters[0].variants!.length, 0);
assert.deepEqual(clean.shots.map(s => appearanceContentHash(s, 'video')), hashes);
assert.equal(cleanupAppearanceVariants(clean.project, clean.shots).retired.length, 0);
assert.equal(appearanceAssetPatch(clean.project, clean.shots).characters[0].variants!.length, 0, 'retired text variants stay retired after resave');
for (const property of [{ cleanReferenceImageUrl: '/authored.png' }, { boardPrompt: '作者提示词' }, { name: '作者名字' }, { referenceVariantId: 'parent' }]) {
 const protectedProject = structuredClone(oldProject); Object.assign(protectedProject.characters[0].variants![0], property);
 assert.equal(cleanupAppearanceVariants(protectedProject, oldShots).retired.length, 1, 'preserve author work');
}
const protectedId = oldProject.characters[0].variants![0].id;
assert.equal(cleanupAppearanceVariants(oldProject, oldShots, [{ history: { reference: protectedId } }]).retired.length, 1);
assert.equal(cleanupAppearanceVariants(oldProject, oldShots, [{ history: `variant:${protectedId}` }]).retired.length, 1);
const mirrored = structuredClone(oldProject); mirrored.assets = [{ id: 'char-c', variants: [{ ...mirrored.characters[0].variants![0], cleanReferenceImageUrl: '/mirror-image.png' }] }] as any;
assert.equal(cleanupAppearanceVariants(mirrored, oldShots).retired.length, 1, 'media in mirrored owner records also pins variants');
const foreign = structuredClone(oldShots[0]); foreign.id = 'unknown-owner'; foreign.appearance!.states[0].assetId = 'other-owner';
assert.equal(cleanupAppearanceVariants(oldProject, [...oldShots, foreign]).retired.length, 0, 'unknown-owner references are not silently stripped');
const promptHistory = [{ manualStoryboard: { boards: [{ boardRecord: { audit: { confirmedPrompt: `旧调用全文 ${protectedId}` } } }], batchAudits: [{ promptExecutions: [{ prompt: `旧调用全文 ${protectedId}` }] }] } }];
const historicalCopy = JSON.stringify(promptHistory);
assert.equal(cleanupAppearanceVariants(oldProject, oldShots, promptHistory).retired.length, 2, 'historical prompt text must not keep a redundant asset alive');
assert.equal(JSON.stringify(promptHistory), historicalCopy, 'original prompt history is unchanged');
assert.equal(cleanupAppearanceVariants(oldProject, oldShots, [{ data: JSON.stringify(promptHistory[0]) }]).retired.length, 2, 'JSON database columns follow the same audit rule');
assert.equal(cleanupAppearanceVariants(oldProject, oldShots, [{ audit: { confirmedPrompt: protectedId, imageReferenceManifest: [{ variantId: protectedId }] } }]).retired.length, 1, 'a real image binding inside an audit still pins');
const from = oldProject.characters[0].variants![1];
const plan = [{ assetId: 'c', variantId: from.id, fingerprint: from.appearanceFingerprint!, replacementVariantId: protectedId }];
const redirected = cleanupAppearanceVariants(oldProject, auto.shots, [], plan);
assert.equal(redirected.retired.length, 1);
assert.equal(redirected.shots[0].appearance!.states[0].endVariantId, protectedId);
assert.equal(redirected.shots[0].appearance!.states[0].referenceNeed, 'text');
assert.equal(redirected.shots[0].appearance!.states[0].end.injury, '指尖少量血迹');
assert.throws(() => cleanupAppearanceVariants(oldProject, auto.shots, [], [{ ...plan[0], fingerprint: 'stale' }]), /停止迁移/);
const oldTemplate = '作者前缀\n【镜头外观与连续性 appearance.v1】\n旧内容\n旧版没有 appearance 的返回仍可解析，但不代表已检查。\n作者后缀';
const upgraded = upgradeAppearanceTemplate(oldTemplate);
assert(upgraded.startsWith('作者前缀')); assert(upgraded.endsWith('作者后缀')); assert(!upgraded.includes('appearance.v1'));
assert.equal(upgradeAppearanceTemplate(upgraded), upgraded);
assert.equal(upgradeAppearanceTemplate(oldTemplate.replace('appearance.v1', 'appearance.v2')), upgraded);
assert(upgraded.includes('只写图片中能看见的'));
assert(upgraded.includes('右手食指少量出血'));
const workspaceScene = { id: 's', manualStoryboard: { schemaVersion: 'manual-storyboard.v1', updatedAt: 1,
 shotPlan: { sourceHash: 'source', outputHash: buildManualShotPlanHash(oldShots), audit: { original: 'keep receipt' } },
 imagePrompts: { sourceHash: buildManualVisualPromptSourceHash('source', oldShots), audit: { original: 'keep prompt' } } } } as any;
const rebased = rebaseAppearanceBookkeeping(workspaceScene, oldShots, clean.shots);
assert.equal(rebased.manualStoryboard!.shotPlan!.outputHash, buildManualShotPlanHash(clean.shots));
assert.equal(rebased.manualStoryboard!.imagePrompts!.sourceHash, buildManualVisualPromptSourceHash('source', clean.shots));
assert.deepEqual(rebased.manualStoryboard!.shotPlan!.audit, workspaceScene.manualStoryboard.shotPlan.audit);
const staleScene = structuredClone(workspaceScene); staleScene.manualStoryboard.shotPlan.outputHash = 'already stale';
assert.deepEqual(rebaseAppearanceBookkeeping(staleScene, oldShots, clean.shots), staleScene, 'migration cannot bless an already-stale approval');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'appearance-cleanup-'));
const file = path.join(dir, 'test.db');
try {
 const db = new Database(file);
 db.exec('CREATE TABLE projects(id TEXT PRIMARY KEY, data TEXT); CREATE TABLE shots(id TEXT PRIMARY KEY, project_id TEXT, scene_id TEXT, order_index INTEGER, data TEXT); CREATE TABLE episodes(id TEXT, project_id TEXT, data TEXT); CREATE TABLE scenes(id TEXT, project_id TEXT, data TEXT);');
 db.prepare('INSERT INTO projects VALUES (?, ?)').run('p', JSON.stringify(oldProject));
 db.prepare('INSERT INTO scenes VALUES (?, ?, ?)').run('s', 'p', JSON.stringify(workspaceScene));
 db.prepare('INSERT INTO projects VALUES (?, ?)').run('untouched', '{"source":"original"}');
 for (const s of oldShots) db.prepare('INSERT INTO shots VALUES (?, ?, ?, ?, ?)').run(s.id, 'p', 's', 0, JSON.stringify(s));
 assert.equal((await repairAppearanceVariants(file, 'p', false)).retired.length, 2);
 assert.equal(JSON.parse((db.prepare('SELECT data FROM projects WHERE id = ?').get('p') as any).data).characters[0].variants.length, 2);
 db.exec("CREATE TRIGGER fail_shots BEFORE UPDATE ON shots BEGIN SELECT RAISE(ABORT, 'test rollback'); END;");
 await assert.rejects(repairAppearanceVariants(file, 'p', true), /test rollback/);
 assert.equal(JSON.parse((db.prepare('SELECT data FROM projects WHERE id = ?').get('p') as any).data).characters[0].variants.length, 2, 'project and shots roll back together');
 db.exec('DROP TRIGGER fail_shots');
 const report = await repairAppearanceVariants(file, 'p', true);
 assert(report.applied && fs.existsSync(report.backup));
 assert.equal(report.rebasedScenes, 1);
 assert.equal(JSON.parse((db.prepare('SELECT data FROM scenes WHERE id = ?').get('s') as any).data).manualStoryboard.shotPlan.outputHash, buildManualShotPlanHash(clean.shots));
 const backup = new Database(report.backup, { readonly: true });
 assert.equal(JSON.parse((backup.prepare('SELECT data FROM projects WHERE id = ?').get('p') as any).data).characters[0].variants.length, 2); backup.close();
 assert.equal((db.prepare('SELECT data FROM projects WHERE id = ?').get('untouched') as any).data, '{"source":"original"}');
 assert.deepEqual((db.prepare('SELECT data FROM shots').all() as any[]).map(r => appearanceContentHash(JSON.parse(r.data), 'video')), hashes);
 assert.equal((await repairAppearanceVariants(file, 'p', true)).retired.length, 0);
 db.close();
} finally { fs.rmSync(dir, { recursive: true, force: true }); }
console.log('通过：文字不建资产、同批参考继承、局部变化保留、历史/媒体保护、迁移备份/原子回滚/幂等、自定义提示词升级。');
