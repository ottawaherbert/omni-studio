import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import type { Project, Episode, Scene } from '../src/types/project';
import { buildStoryboardBatchSceneReadModel, buildStoryboardTeamPromptContext } from '../src/services/production/storyboardBatchSceneIndex';
import { buildProductionPreparationGate } from '../src/services/production/productionPreparationGate';
import { buildProductionPreparationCurrentTask, productionPreparationTabs, resolveProductionSceneTab } from '../src/features/production/preparation/productionPreparationViewModel';
import { upgradeDirectProductionTemplate } from '../src/config/prompts/directProductionContract';
import { assistantCapabilityRegistry } from '../src/services/assistant/capabilities';

const fixture = JSON.parse(readFileSync('tests/fixtures/production/simple-preparation/fixture.json', 'utf8')) as Project;
const episode = structuredClone(fixture.episodes[0]) as Episode;
delete episode.productionTeam;
delete episode.simplePreparation;
episode.scenes[0].shots = [{ id: 'prior-shot', visualAction: '周宁接过铜钥匙，握在右手。', continuityNote: '铜钥匙在周宁右手；下一场继续持有。', characterIdsInShot: ['simple-ui-zhou'], propIds: ['simple-ui-key'] }] as Scene['shots'];
episode.scenes[1].breakdown!.propIds = ['simple-ui-key'];
const project = { ...fixture, episodes: [episode] };
const scene = episode.scenes[1];
const before = JSON.stringify(project);
const model = buildStoryboardBatchSceneReadModel({ project, episode, episodes: [episode], scene });
assert.equal(model.productionReady, true, 'a scene with no department outputs can enter shot planning');
assert.equal(model.assets.issues.some(issue => /(?:部门|筹备).*(?:缺少|尚未|未确认)|(?:缺少|尚未).*(?:部门|筹备)/.test(issue.message)), false);
assert.ok(model.assets.assetBoards.some(board => board.assetId === 'simple-ui-key'), 'canonical props remain bound without a department report');
assert.ok(model.assets.assetBoards.every(board => board.departmentBlockers.length === 0));
const context = JSON.parse(model.filmTeamContext);
assert.equal(context.currentScene.source, scene.script);
assert.equal(context.adjacentScenes[0].source, episode.scenes[0].script);
assert.equal(context.previousSceneEnding[0].continuityNote, episode.scenes[0].shots[0].continuityNote);
assert.deepEqual(context.historicalPlans, []);
assert.equal(JSON.stringify(project), before, 'read-only context construction must not invent or persist preparation results');
const rawScene = { ...scene, breakdown: undefined, productionPreparation: undefined };
const rawModel = buildStoryboardBatchSceneReadModel({ project, episode, episodes: [episode], scene: rawScene });
assert.ok(rawModel.allowedAssetIds.character.includes('simple-ui-zhou'));
assert.ok(rawModel.allowedAssetIds.prop.includes('simple-ui-key'));
assert.ok(JSON.parse(rawModel.assetContext).availableProjectAssets.some(item => item.assetId === 'simple-ui-key'));
assert.equal(rawModel.productionReady, true, 'raw script can proceed without an approved breakdown');
const gate = buildProductionPreparationGate({ scene: rawScene, filmTeam: rawModel.filmTeam, assets: rawModel.assets });
assert.ok(!gate.advisories.some(message => /部门|统筹|先.*拆解/.test(message)), 'removed workflow steps cannot survive as required recommendations');
assert.equal(buildProductionPreparationCurrentTask({ scene, filmTeam: model.filmTeam, assets: model.assets }).tab, 'assets');
assert.deepEqual(productionPreparationTabs.map(tab => tab.id), ['overview', 'breakdown', 'assets']);
for (const legacyTab of ['departments', 'review']) assert.equal(resolveProductionSceneTab(legacyTab, scene, episode), 'assets');
for (const tab of ['assets', 'breakdown', 'departments', 'review']) assert.equal(resolveProductionSceneTab(tab), 'overview', 'empty units must remain on the source overview');
assert.equal(assistantCapabilityRegistry.some(item => item.id === 'production.auto_prepare_unit' || item.id === 'production.adopt_preparation_batch'), false, 'assistant cannot reintroduce the removed report workflow');
const customPrompt = '作者自定义风格：黑白默片。\n【已确认的制片筹备结果】\n{{productionTeamContext}}';
const upgraded = upgradeDirectProductionTemplate(customPrompt);
assert.ok(upgraded.includes('作者自定义风格：黑白默片。'));
assert.ok(upgraded.includes('缺少历史方案时依据原文和作者要求完成'));
assert.equal(upgradeDirectProductionTemplate(upgraded), upgraded);
const legacy = structuredClone(episode);
legacy.productionTeam = { outputs: [{ department: 'directing', status: 'confirmed', taskSummary: '既有人工定调', content: '低机位表现空间压迫', scenePlans: [{ sceneId: scene.id, summary: '保留此场人工调度' }], handoffNotes: [] }] } as Episode['productionTeam'];
assert.equal(JSON.parse(buildStoryboardTeamPromptContext(legacy, scene)).historicalPlans[0].unitPlan, '低机位表现空间压迫');
assert.equal(buildStoryboardTeamPromptContext({ ...episode, __workspaceProductionTeamSummaryOnly: true } as Episode, scene), '', 'summary projections must request fresh full source context');
console.log('Direct production passed: raw-script entry, canonical asset reuse, adjacent source and prior-shot continuity, optional legacy context, preserved author prompts and retired workflow navigation.');
